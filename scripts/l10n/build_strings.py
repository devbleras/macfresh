#!/usr/bin/env python3
"""Checks that every L("…")/LF("…") key has an English translation and writes the .lproj files.

Usage: python3 scripts/l10n/build_strings.py
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from en import EN, INFOPLIST_EN, INFOPLIST_ES  # noqa: E402

KEY_RE = re.compile(r'\bLF?\("((?:[^"\\]|\\.)*)"')
keys = set()
for f in (ROOT / "Sources").rglob("*.swift"):
    keys.update(KEY_RE.findall(f.read_text()))

missing = sorted(k for k in keys if k not in EN)
unused = sorted(k for k in EN if k not in keys)
if unused:
    print(f"⚠︎ {len(unused)} unused translations:", *unused, sep="\n  ")
if missing:
    print(f"✗ {len(missing)} keys without English translation:", *missing, sep="\n  ")
    sys.exit(1)

def write(path, mapping):
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["/* Generated by scripts/l10n/build_strings.py — edit scripts/l10n/en.py instead. */", ""]
    for k in sorted(mapping):
        lines.append(f'"{k}" = "{mapping[k]}";')
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")

res = ROOT / "Resources"
write(res / "en.lproj" / "Localizable.strings", {k: (EN[k] if EN[k] is not None else k) for k in keys})
write(res / "es.lproj" / "Localizable.strings", {k: k for k in keys})
write(res / "en.lproj" / "InfoPlist.strings", INFOPLIST_EN)
write(res / "es.lproj" / "InfoPlist.strings", INFOPLIST_ES)
print(f"✓ {len(keys)} keys localized (es, en)")
